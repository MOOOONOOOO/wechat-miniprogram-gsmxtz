function getResultCopyPool(matchCount) {
  const normalized = Math.max(0, Math.min(9, Number(matchCount) || 0));
  return Array.from(new Set(copyByMatchCount[normalized] || copyByMatchCount[0]));
}

function pickResultCopy(matchCount, usedCopies) {
  const list = getResultCopyPool(matchCount);
  const used = Array.isArray(usedCopies) ? usedCopies : (usedCopies ? [usedCopies] : []);
  let candidates = list.length > 1 ? list.filter((item) => used.indexOf(item) === -1) : list;
  if (!candidates.length) candidates = list;
  const index = Math.floor(Math.random() * candidates.length);
  return candidates[index] || list[0];
}

